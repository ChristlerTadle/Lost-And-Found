CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name TEXT NOT NULL UNIQUE CHECK (role_name IN ('user', 'staff', 'admin'))
);

INSERT INTO roles (role_name) VALUES ('user'), ('staff'), ('admin')
ON CONFLICT (role_name) DO NOTHING;

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id SMALLINT NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    email CITEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    student_id TEXT,
    employee_id TEXT,
    department TEXT,
    phone TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(full_name)) > 0),
    CHECK (student_id IS NOT NULL OR employee_id IS NOT NULL)
);

CREATE UNIQUE INDEX users_student_id_unique ON users (student_id) WHERE student_id IS NOT NULL;
CREATE UNIQUE INDEX users_employee_id_unique ON users (employee_id) WHERE employee_id IS NOT NULL;

CREATE TABLE lost_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    item_type TEXT NOT NULL DEFAULT 'lost' CHECK (item_type IN ('lost', 'found')),
    item_name TEXT NOT NULL,
    description TEXT NOT NULL,
    identifying_details TEXT NOT NULL,
    category TEXT NOT NULL,
    location TEXT NOT NULL,
    date_lost DATE NOT NULL,
    image_path TEXT,
    status TEXT NOT NULL DEFAULT 'lost' CHECK (status IN ('lost', 'found', 'cancelled', 'claimed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX lost_items_user_id_idx ON lost_items (user_id);
CREATE INDEX lost_items_date_lost_idx ON lost_items (date_lost);

CREATE TABLE item_claims (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    item_id UUID NOT NULL REFERENCES lost_items (id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    claim_details TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (item_id, user_id),
    CHECK (length(trim(claim_details)) > 0)
);

CREATE INDEX item_claims_user_id_idx ON item_claims (user_id);
