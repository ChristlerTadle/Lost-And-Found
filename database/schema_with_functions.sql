-- Complete PostgreSQL MVP schema and stored functions.
-- Scope: registration, login, profile view/edit, and lost report create/view/edit.
-- Requires PostgreSQL 13+.

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS roles (
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   TEXT NOT NULL UNIQUE,
    CONSTRAINT roles_role_name_check
        CHECK (role_name IN ('user', 'staff', 'admin'))
);

INSERT INTO roles (role_name)
VALUES ('user'), ('staff'), ('admin')
ON CONFLICT (role_name) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id         SMALLINT NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    email           CITEXT NOT NULL UNIQUE,
    password_hash   TEXT NOT NULL,
    full_name       TEXT NOT NULL,
    student_id      TEXT,
    employee_id     TEXT,
    department      TEXT,
    phone           TEXT,
    status          TEXT NOT NULL DEFAULT 'active',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_full_name_check CHECK (length(trim(full_name)) > 0),
    CONSTRAINT users_status_check CHECK (status IN ('active', 'disabled')),
    CONSTRAINT users_identity_check CHECK (student_id IS NOT NULL OR employee_id IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS users_student_id_unique
    ON users (student_id) WHERE student_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS users_employee_id_unique
    ON users (employee_id) WHERE employee_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS lost_items (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    item_type           TEXT NOT NULL DEFAULT 'lost',
    item_name           TEXT NOT NULL,
    description         TEXT NOT NULL,
    identifying_details TEXT NOT NULL,
    category            TEXT NOT NULL,
    location            TEXT NOT NULL,
    date_lost           DATE NOT NULL,
    image_path          TEXT,
    status              TEXT NOT NULL DEFAULT 'lost',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lost_items_type_check CHECK (item_type IN ('lost', 'found')),
    CONSTRAINT lost_items_status_check CHECK (status IN ('lost', 'found', 'cancelled', 'claimed')),
    CONSTRAINT lost_items_required_text_check CHECK (
        length(trim(item_name)) > 0
        AND length(trim(description)) > 0
        AND length(trim(identifying_details)) > 0
        AND length(trim(category)) > 0
        AND length(trim(location)) > 0
    )
);

CREATE INDEX IF NOT EXISTS lost_items_user_id_idx ON lost_items (user_id);
CREATE INDEX IF NOT EXISTS lost_items_date_lost_idx ON lost_items (date_lost);

CREATE TABLE IF NOT EXISTS item_claims (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    item_id             UUID NOT NULL REFERENCES lost_items (id) ON DELETE CASCADE,
    user_id             UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    claim_details       TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'pending',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT item_claims_status_check CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT item_claims_details_check CHECK (length(trim(claim_details)) > 0),
    CONSTRAINT item_claims_item_user_unique UNIQUE (item_id, user_id)
);

CREATE INDEX IF NOT EXISTS item_claims_user_id_idx ON item_claims (user_id);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS lost_items_set_updated_at ON lost_items;
CREATE TRIGGER lost_items_set_updated_at
BEFORE UPDATE ON lost_items
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Creates public accounts with the user role only.
-- password_hash should be produced by PHP password_hash(PASSWORD_DEFAULT).
CREATE OR REPLACE FUNCTION register_user(
    p_email TEXT,
    p_password_hash TEXT,
    p_full_name TEXT,
    p_student_id TEXT DEFAULT NULL,
    p_department TEXT DEFAULT NULL,
    p_phone TEXT DEFAULT NULL
)
RETURNS TABLE (
    id UUID,
    email CITEXT,
    full_name TEXT,
    student_id TEXT,
    department TEXT,
    phone TEXT,
    role_name TEXT,
    status TEXT,
    created_at TIMESTAMPTZ
)
LANGUAGE plpgsql
AS $$
DECLARE
    user_role_id SMALLINT;
BEGIN
    IF trim(p_email) = '' OR trim(p_password_hash) = '' OR trim(p_full_name) = '' THEN
        RAISE EXCEPTION 'Email, password hash, and full name are required';
    END IF;

    SELECT r.id INTO user_role_id FROM roles AS r WHERE r.role_name = 'user';

    IF user_role_id IS NULL THEN
        RAISE EXCEPTION 'Default user role is not configured';
    END IF;

    RETURN QUERY
    INSERT INTO users (
        role_id, email, password_hash, full_name, student_id, department, phone
    )
    VALUES (
        user_role_id,
        lower(trim(p_email)),
        p_password_hash,
        trim(p_full_name),
        NULLIF(trim(p_student_id), ''),
        NULLIF(trim(p_department), ''),
        NULLIF(trim(p_phone), '')
    )
    RETURNING users.id,
              users.email,
              users.full_name,
              users.student_id,
              users.department,
              users.phone,
              'user'::TEXT,
              users.status,
              users.created_at;
END;
$$;

-- Returns an active account when the supplied hash matches the stored hash.
-- This supports bcrypt hashes generated by PHP password_hash().
CREATE OR REPLACE FUNCTION authenticate_user(
    p_email TEXT,
    p_password TEXT
)
RETURNS TABLE (
    id UUID,
    email CITEXT,
    full_name TEXT,
    student_id TEXT,
    employee_id TEXT,
    department TEXT,
    phone TEXT,
    role_id SMALLINT,
    role_name TEXT,
    status TEXT,
    created_at TIMESTAMPTZ
)
LANGUAGE sql
STABLE
AS $$
    SELECT u.id,
           u.email,
           u.full_name,
           u.student_id,
           u.employee_id,
           u.department,
           u.phone,
           r.id,
           r.role_name,
           u.status,
           u.created_at
    FROM users AS u
    INNER JOIN roles AS r ON r.id = u.role_id
    WHERE u.email = lower(trim(p_email))
      AND u.status = 'active'
      AND u.password_hash = crypt(p_password, u.password_hash);
$$;

CREATE OR REPLACE FUNCTION get_profile(p_user_id UUID)
RETURNS TABLE (
    id UUID,
    email CITEXT,
    full_name TEXT,
    student_id TEXT,
    employee_id TEXT,
    department TEXT,
    phone TEXT,
    role_id SMALLINT,
    role_name TEXT,
    status TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
)
LANGUAGE sql
STABLE
AS $$
    SELECT u.id,
           u.email,
           u.full_name,
           u.student_id,
           u.employee_id,
           u.department,
           u.phone,
           r.id,
           r.role_name,
           u.status,
           u.created_at,
           u.updated_at
    FROM users AS u
    INNER JOIN roles AS r ON r.id = u.role_id
    WHERE u.id = p_user_id;
$$;

CREATE OR REPLACE FUNCTION update_profile(
    p_user_id UUID,
    p_full_name TEXT,
    p_department TEXT DEFAULT NULL,
    p_phone TEXT DEFAULT NULL
)
RETURNS TABLE (
    id UUID,
    email CITEXT,
    full_name TEXT,
    student_id TEXT,
    employee_id TEXT,
    department TEXT,
    phone TEXT,
    status TEXT,
    updated_at TIMESTAMPTZ
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF trim(p_full_name) = '' THEN
        RAISE EXCEPTION 'Full name is required';
    END IF;

    RETURN QUERY
    UPDATE users AS u
    SET full_name = trim(p_full_name),
        department = NULLIF(trim(p_department), ''),
        phone = NULLIF(trim(p_phone), '')
    WHERE u.id = p_user_id
      AND u.status = 'active'
    RETURNING u.id,
              u.email,
              u.full_name,
              u.student_id,
              u.employee_id,
              u.department,
              u.phone,
              u.status,
              u.updated_at;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Active user was not found';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION create_lost_item(
    p_user_id UUID,
    p_item_name TEXT,
    p_description TEXT,
    p_identifying_details TEXT,
    p_category TEXT,
    p_location TEXT,
    p_date_lost DATE
)
RETURNS lost_items
LANGUAGE plpgsql
AS $$
DECLARE
    created_item lost_items;
BEGIN
    INSERT INTO lost_items (
        user_id, item_name, description, identifying_details, category, location, date_lost
    )
    VALUES (
        p_user_id,
        trim(p_item_name),
        trim(p_description),
        trim(p_identifying_details),
        trim(p_category),
        trim(p_location),
        p_date_lost
    )
    RETURNING * INTO created_item;

    RETURN created_item;
END;
$$;

CREATE OR REPLACE FUNCTION list_my_lost_items(p_user_id UUID)
RETURNS SETOF lost_items
LANGUAGE sql
STABLE
AS $$
    SELECT li.*
    FROM lost_items AS li
    WHERE li.user_id = p_user_id
    ORDER BY li.created_at DESC;
$$;

CREATE OR REPLACE FUNCTION update_lost_item(
    p_user_id UUID,
    p_item_id UUID,
    p_item_name TEXT,
    p_description TEXT,
    p_identifying_details TEXT,
    p_category TEXT,
    p_location TEXT,
    p_date_lost DATE
)
RETURNS lost_items
LANGUAGE plpgsql
AS $$
DECLARE
    updated_item lost_items;
BEGIN
    UPDATE lost_items AS li
    SET item_name = trim(p_item_name),
        description = trim(p_description),
        identifying_details = trim(p_identifying_details),
        category = trim(p_category),
        location = trim(p_location),
        date_lost = p_date_lost
    WHERE li.id = p_item_id
      AND li.user_id = p_user_id
      AND li.status = 'lost'
    RETURNING li.* INTO updated_item;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Editable lost report was not found';
    END IF;

    RETURN updated_item;
END;
$$;

-- Role helper for application middleware and administrative seed checks.
CREATE OR REPLACE FUNCTION user_has_role(
    p_user_id UUID,
    p_role_name TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM users AS u
        INNER JOIN roles AS r ON r.id = u.role_id
        WHERE u.id = p_user_id
          AND u.status = 'active'
          AND r.role_name = p_role_name
    );
$$;
